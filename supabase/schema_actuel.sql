CREATE OR REPLACE FUNCTION public.teacher_can_access_class(p_class_id bigint) RETURNS boolean
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public', 'pg_temp' AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles p
    JOIN public.teachers t ON t.school_id = p.school_id AND t.matricule = p.matricule
    JOIN public.teacher_slots ts ON ts.school_id = t.school_id AND ts.teacher_id = t.id
    WHERE p.id = auth.uid() AND p.role = 'teacher'
      AND p.school_id = my_school_id() AND ts.class_id = p_class_id
  )
$function$;

CREATE OR REPLACE FUNCTION public.teacher_can_edit_grade(p_student_id bigint, p_subject_id bigint) RETURNS boolean
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public', 'pg_temp' AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles p
    JOIN public.teachers t ON t.school_id = p.school_id AND t.matricule = p.matricule
    JOIN public.students st ON st.school_id = p.school_id AND st.id = p_student_id
    JOIN public.subjects sub ON sub.school_id = p.school_id AND sub.id = p_subject_id
    JOIN public.teacher_slots ts ON ts.school_id = p.school_id
      AND ts.teacher_id = t.id AND ts.class_id = st.class_id
    WHERE p.id = auth.uid() AND p.role = 'teacher'
      AND (sub.teacher_id = t.id OR (
        sub.teacher_id IS NULL
        AND (
          lower(trim(t.subject)) = lower(trim(sub.name))
          OR lower(trim(t.subject)) LIKE lower(trim(sub.name)) || ' (%'
        )
      ))
  )
$function$;

CREATE OR REPLACE FUNCTION public.teacher_can_take_attendance(p_class_id bigint, p_student_id bigint) RETURNS boolean
